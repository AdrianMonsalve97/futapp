import Database from 'better-sqlite3';
import { migrate } from './migrate';
import { postgresQuery, type PostgresDatabase } from './postgres-database';
import { DEFAULT_NOTIFICATION_SETTINGS } from '../../../domain/notifications';

/** Both databases are built from the same trusted schema, keeping snapshots compatible. */
export function canonicalSchema() {
  const db = new Database(':memory:');
  try {
    migrate(db);
    const tables = db.prepare("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all() as {name:string;sql:string}[];
    const indexes = db.prepare("SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL AND name NOT LIKE 'sqlite_%'").all() as {sql:string}[];
    return { tables:tables.map(table => ({...table,columns:(db.pragma(`table_info(${table.name})`) as {name:string}[]).map(column=>column.name)})),indexes };
  } finally { db.close(); }
}

export async function migratePostgres(db: PostgresDatabase) {
  const schema = canonicalSchema();
  await db.execute('CREATE SCHEMA IF NOT EXISTS futapp');
  await db.transaction(async () => {
    await db.query("SELECT pg_advisory_xact_lock(hashtextextended('futapp-schema-v1',0))");
    const remaining = [...schema.tables], created = new Set<string>();
    while (remaining.length) {
      const ready = remaining.findIndex(table => [...table.sql.matchAll(/\bREFERENCES\s+([a-z_]+)/gi)].every(match => created.has(match[1])));
      if (ready < 0) throw new Error('El esquema contiene referencias circulares');
      const [table] = remaining.splice(ready,1);
      const sql = postgresQuery(table.sql,[]).text
        .replace(/\bINTEGER PRIMARY KEY AUTOINCREMENT\b/gi,'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
        .replace(/\bINTEGER\b/gi,'BIGINT').replace(/\bREAL\b/gi,'DOUBLE PRECISION')
        .replace(/(REFERENCES\s+\w+\s*\(\w+\)(?:\s+ON DELETE (?:CASCADE|SET NULL))?)/gi,'$1 DEFERRABLE INITIALLY IMMEDIATE')
        .replace(/^CREATE TABLE\s+(?:IF NOT EXISTS\s+)?/i,'CREATE TABLE IF NOT EXISTS ');
      await db.execute(sql);created.add(table.name);
      if(table.name==='auth_sessions') {
        const activity=await db.query("SELECT column_name FROM information_schema.columns WHERE table_schema='futapp' AND table_name='auth_sessions' AND column_name='last_activity_at'");
        if(!activity.length){
          await db.execute('ALTER TABLE auth_sessions ADD COLUMN last_activity_at BIGINT NOT NULL DEFAULT 0');
          await db.prepare('UPDATE auth_sessions SET last_activity_at=?').run(Date.now());
        }
      }
      const columns=await db.query("SELECT column_name FROM information_schema.columns WHERE table_schema='futapp' AND table_name=$1",[table.name]);
      if(columns.map(row=>row.column_name).sort().join()!==[...table.columns].sort().join())throw new Error('El esquema de PostgreSQL necesita una migración de versión antes de iniciar');
    }
    for(const index of schema.indexes)await db.execute(index.sql.replace(/^CREATE UNIQUE INDEX /,'CREATE UNIQUE INDEX IF NOT EXISTS ').replace(/^CREATE INDEX /,'CREATE INDEX IF NOT EXISTS '));
    // Versioned CHECK extension: preserve every existing receipt and its references.
    const checks=await db.query("SELECT conname,pg_get_constraintdef(oid) AS definition FROM pg_constraint WHERE conrelid='futapp.payment_receipts'::regclass AND contype='c'");
    for (const check of checks.filter(row=>/\bkind\b/.test(row.definition) && !row.definition.includes('referee'))) {
      if (!/^[a-z_][a-z0-9_]*$/.test(check.conname)) throw new Error('Restricción de pagos no compatible');
      await db.execute(`ALTER TABLE payment_receipts DROP CONSTRAINT "${check.conname}"`);
      await db.execute("ALTER TABLE payment_receipts ADD CONSTRAINT payment_receipts_kind_check CHECK(kind IN ('inscription','uniform_request','uniform_issue','referee'))");
    }
    await db.execute("INSERT INTO match_referee_fees(match_id) SELECT id FROM matches WHERE status IN ('programado','pospuesto') ON CONFLICT DO NOTHING");
    const uniformChecks=await db.query("SELECT conname,pg_get_constraintdef(oid) AS definition FROM pg_constraint WHERE conrelid='futapp.uniforms'::regclass AND contype='c'");
    for(const check of uniformChecks.filter(row=>/\bkind\b/.test(row.definition)&&!row.definition.includes('completo'))) {
      if(!/^[a-z_][a-z0-9_]*$/.test(check.conname))throw new Error('Restricción de uniformes no compatible');
      await db.execute(`ALTER TABLE uniforms DROP CONSTRAINT "${check.conname}"`);
      await db.execute("ALTER TABLE uniforms ADD CONSTRAINT uniforms_kind_check CHECK(kind IN ('completo','camiseta','pantalon','medias','buzo','entrenamiento','guantes'))");
    }
    await db.prepare("INSERT OR IGNORE INTO team_settings(id,team_name,format,season) VALUES(1,'Club Portal',8,'2026')").run();
    await db.prepare('INSERT OR IGNORE INTO migration_state(id) VALUES(1)').run();
    await db.prepare('INSERT OR IGNORE INTO qr_payment_settings(id) VALUES(1)').run();
    await db.prepare('INSERT OR IGNORE INTO notification_settings(id,config) VALUES(1,?)').run(JSON.stringify(DEFAULT_NOTIFICATION_SETTINGS));
    await db.execute('CREATE TABLE IF NOT EXISTS model_artifacts(id BIGINT PRIMARY KEY CHECK(id=1),data TEXT NOT NULL)');
    // No application tables are exposed through Supabase's public API.
    await db.execute(`REVOKE ALL ON SCHEMA futapp FROM PUBLIC;
      DO $$ BEGIN
        IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='anon') THEN REVOKE ALL ON SCHEMA futapp FROM anon; REVOKE ALL ON ALL TABLES IN SCHEMA futapp FROM anon; END IF;
        IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname='authenticated') THEN REVOKE ALL ON SCHEMA futapp FROM authenticated; REVOKE ALL ON ALL TABLES IN SCHEMA futapp FROM authenticated; END IF;
      END $$;`);
  })();
}
